-- اللوحة الإدارية — QuickData
-- الخطوة 9: السكن + مخالفات السيارات + "أخرى" (تطوير) + تعديلات
--           السيارات والتواصل بين الإدارات
-- شغّل الملف ده كله مرة واحدة في Supabase → SQL Editor.
-- آمن لإعادة التشغيل (IF NOT EXISTS / DROP IF EXISTS).
