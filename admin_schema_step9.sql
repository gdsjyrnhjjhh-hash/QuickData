create extension if not exists pgcrypto;

-- ================================================================
-- 1) السكن  (admin_housing)
--    serial_no: رقم مسلسل تلقائي
-- ================================================================
create table if not exists public.admin_housing (
    id uuid primary key default gen_random_uuid(),
    serial_no bigint generated by default as identity,
    housing_name text not null,        -- مثال: الساحلي / الفرقان / الإدارة
    room_number text,
    employee_name text,
    room_contents text,                -- محتويات الغرفة (نص حر)
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);
create index if not exists idx_admin_housing_name on public.admin_housing (housing_name);

-- ================================================================
-- 2) مخالفات السيارات  (admin_traffic_fines)
-- ================================================================
create table if not exists public.admin_traffic_fines (
    id uuid primary key default gen_random_uuid(),
    serial_no bigint generated by default as identity,
    violation_name text not null,
    violation_date date,
    violator_name text,
    department text,
    amount numeric(12,2),
    deduction_method text,             -- طريقة الخصم (نص حر)
    is_deducted boolean not null default false,   -- الوضع: تم الخصم / لم يتم
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);
create index if not exists idx_admin_traffic_fines_deducted on public.admin_traffic_fines (is_deducted);
create index if not exists idx_admin_traffic_fines_date on public.admin_traffic_fines (violation_date);

-- ================================================================
-- 3) "أخرى" في تطوير الأفكار — ورقة عمل حرة  (admin_other_notes)
-- ================================================================
create table if not exists public.admin_other_notes (
    id uuid primary key default gen_random_uuid(),
    title text not null,
    content text,                      -- بدون حد للكتابة
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

-- ================================================================
-- 4) السيارات: رقم الهيكل + بند "أخرى" بجانب الحالة
-- ================================================================
alter table public.admin_vehicles add column if not exists chassis_number text;
alter table public.admin_vehicles add column if not exists status_other text;

-- لو كان على عمود status قيد CHECK قديم بيمنع القيمة الجديدة 'other'، نشيله
do $$
declare r record;
begin
    for r in
        select c.conname
        from pg_constraint c
        where c.conrelid = 'public.admin_vehicles'::regclass
          and c.contype = 'c'
          and pg_get_constraintdef(c.oid) ilike '%status%'
    loop
        execute format('alter table public.admin_vehicles drop constraint %I', r.conname);
    end loop;
end $$;

-- ================================================================
-- 5) التواصل بين الإدارات: نص المخاطبة (حر + قابل للتعديل)
-- ================================================================
alter table public.admin_correspondence add column if not exists body text;
alter table public.admin_correspondence add column if not exists updated_at timestamptz default now();

-- ================================================================
-- 6) الحماية على مستوى الصفوف (نفس سياسة باقي الجداول)
-- ================================================================
alter table public.admin_housing enable row level security;
drop policy if exists "admin_housing_all" on public.admin_housing;
create policy "admin_housing_all" on public.admin_housing for all
    using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

alter table public.admin_traffic_fines enable row level security;
drop policy if exists "admin_traffic_fines_all" on public.admin_traffic_fines;
create policy "admin_traffic_fines_all" on public.admin_traffic_fines for all
    using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

alter table public.admin_other_notes enable row level security;
drop policy if exists "admin_other_notes_all" on public.admin_other_notes;
create policy "admin_other_notes_all" on public.admin_other_notes for all
    using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

